// jsdom does not implement matchMedia or window.scrollTo, which the app shell uses.
if (!window.matchMedia) {
  window.matchMedia = ((query: string) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  })) as typeof window.matchMedia;
}

window.scrollTo = (() => {}) as typeof window.scrollTo;